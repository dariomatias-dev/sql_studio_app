/// Centralized spacing scale used for padding, insets and gaps.
class AppSpacing {
  AppSpacing._();

  /// Hairline gaps between tightly related elements.
  static const double xxs = 4;

  /// Icon-to-label gaps and dense list padding.
  static const double xs = 8;

  /// Compact cards, chips and toolbar padding.
  static const double sm = 12;

  /// Default padding for cards, dialogs and list items.
  static const double md = 16;

  /// Screen-level horizontal padding and gaps between sections.
  static const double lg = 24;

  /// Generous separation between blocks of content.
  static const double xl = 32;

  /// Empty-state and hero-level spacing.
  static const double xxl = 40;
}
